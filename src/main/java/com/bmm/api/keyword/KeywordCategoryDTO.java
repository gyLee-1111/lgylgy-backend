package com.bmm.api.keyword;

public class KeywordCategoryDTO {
	
	private int keywordCode;
	
	private String keycategoryNm;

	private String keycategoryMain;
	
	private int keycategoryRatio;

	public int getKeywordCode() {
		return keywordCode;
	}

	public void setKeywordCode(int keywordCode) {
		this.keywordCode = keywordCode;
	}

	public String getKeycategoryNm() {
		return keycategoryNm;
	}

	public void setKeycategoryNm(String keycategoryNm) {
		this.keycategoryNm = keycategoryNm;
	}

	public String getKeycategoryMain() {
		return keycategoryMain;
	}

	public void setKeycategoryMain(String keycategoryMain) {
		this.keycategoryMain = keycategoryMain;
	}

	public int getKeycategoryRatio() {
		return keycategoryRatio;
	}

	public void setKeycategoryRatio(int keycategoryRatio) {
		this.keycategoryRatio = keycategoryRatio;
	}

	
	
}
